/**
 * The `DCG_CONFIG` policy file this plugin generates and owns.
 *
 * Design: the plugin's settings are the single source of truth; this file is a
 * derived artifact, rewritten atomically whenever the settings change. dcg reads
 * it through `--config`, which is why the terminal keeps using the user's own
 * `~/.config/dcg/config.toml` while Harness sessions follow the plugin.
 *
 * Only configured keys are emitted, so an untouched policy means "dcg's own
 * severity ladder", which is what a guard should default to: block what is
 * genuinely destructive, warn on the recoverable middle, stay quiet otherwise.
 *
 * @module dsh-shell-dcg/lib/policy
 */

import fs from 'node:fs'
import path from 'node:path'

import { generatedDir, policyPath } from './config.js'

const HEADER = [
  '# Generated by dsh-shell-dcg — do not edit by hand.',
  '# Change the plugin settings instead; this file is rewritten on every start',
  '# and on every settings change. dcg reads it through --config, so a terminal',
  '# invocation of dcg keeps using your own user config.',
]

/**
 * Render the policy file for one settings object.
 * @returns the complete TOML text, header included.
 */
export function buildPolicyToml(settings) {
  const { packs, defaultMode, observeUntil, packModes } = settings.policy
  const sections = []

  if (packs.length > 0) {
    // Additive: dcg keeps its own default set and always protects the `core.*`
    // packs, so this list can only switch additional packs on. There is no
    // "off" — the per-pack modes below are the only way to soften a rule.
    sections.push(['[packs]', `enabled = [${packs.map(quote).join(', ')}]`])
  }

  // Written only when someone picked a mode. Left out, dcg applies its own
  // severity ladder (critical/high -> deny, medium -> warn, low -> log); naming
  // a mode here replaces that ladder with one answer for every rule.
  const policyLines = []
  if (defaultMode.length > 0) {
    policyLines.push(`default_mode = ${quote(defaultMode)}`)
  }
  if (observeUntil.length > 0) {
    policyLines.push(`observe_until = ${quote(observeUntil)}`)
  }
  if (policyLines.length > 0) sections.push(['[policy]', ...policyLines])

  const packOverrides = Object.entries(packModes)
  if (packOverrides.length > 0) {
    sections.push(['[policy.packs]', ...packOverrides.map(([packId, mode]) => `${quote(packId)} = ${quote(mode)}`)])
  }

  const body = sections.map((lines) => lines.join('\n')).join('\n\n')
  return `${HEADER.join('\n')}\n\n${body}\n`
}

/**
 * Write the policy file when its content changed.
 * @returns `{ path, written, text }` — `written: false` means it was already current.
 */
export function writePolicy(settings, env = process.env) {
  const target = policyPath(env)
  const text = buildPolicyToml(settings)
  let current
  try {
    current = fs.readFileSync(target, 'utf8')
  } catch {
    current = undefined
  }
  if (current === text) return { path: target, written: false, text }

  fs.mkdirSync(generatedDir(env), { recursive: true })
  const temporary = path.join(path.dirname(target), `.policy.${process.pid}.tmp`)
  fs.writeFileSync(temporary, text, 'utf8')
  fs.renameSync(temporary, target)
  return { path: target, written: true, text }
}

function quote(value) {
  // JSON string escaping is a subset of TOML basic-string escaping for the ids
  // and dates this file carries.
  return JSON.stringify(String(value))
}

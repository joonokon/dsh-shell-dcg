/**
 * Smoke test: pure Node, no Harness runtime.
 *
 * Covers the parts that are easy to get wrong and cheap to check — config
 * normalization, the exact dcg argv, verdict parsing, decision mapping, policy
 * rendering, and the process layer (spawn, timeout, concurrency).
 *
 * Run: node test/smoke.mjs
 */

import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

import {
  compareVersions,
  extractCommand,
  normalizeConfig,
  policyPath,
  auditDir,
} from '../lib/config.js'
import { buildTestArgs, cleanEnv, createLimiter, parseVerdict, resolveBinary, runDcg } from '../lib/dcg.js'
import { mapDecision, reasonFor } from '../lib/gate.js'
import { buildPolicyToml as policyToml } from '../lib/policy.js'

const results = []
async function check(name, fn) {
  try {
    await fn()
    results.push({ name, ok: true })
    process.stdout.write(`ok   ${name}\n`)
  } catch (error) {
    results.push({ name, ok: false, error })
    process.stdout.write(`FAIL ${name}\n     ${error instanceof Error ? error.message : String(error)}\n`)
  }
}

// ---------------------------------------------------------------- config ----

await check('defaults are complete and frozen', () => {
  const { settings, warnings } = normalizeConfig(undefined)
  assert.equal(warnings.length, 0)
  assert.equal(settings.enabled, false)
  assert.equal(settings.failClosed, true)
  assert.equal(settings.onNotReady, 'deny')
  assert.deepEqual(settings.tools, ['ops_bash', 'bash', 'pwsh', 'ssh_exec'])
  assert.equal(settings.dialects.pwsh, 'ps')
  assert.ok(Object.isFrozen(settings))
})

await check('bad values fall back with warnings, never throw', () => {
  const { settings, warnings } = normalizeConfig({
    enabled: 'yes',
    timeoutMs: -5,
    maxConcurrent: 1.5,
    tools: 'ops_bash',
    onAsk: 'maybe',
    dialects: { pwsh: 'cmd', bash: 'posix' },
    policy: { packModes: { 'core.git': 'nope', 'core.fs': 'warn' } },
    audit: { retentionDays: 0 },
  })
  assert.equal(settings.enabled, false)
  assert.equal(settings.timeoutMs, 3000)
  assert.equal(settings.maxConcurrent, 4)
  assert.deepEqual(settings.tools, ['ops_bash', 'bash', 'pwsh', 'ssh_exec'])
  assert.equal(settings.onAsk, 'ask')
  assert.equal(settings.dialects.pwsh, 'ps')
  assert.equal(settings.dialects.bash, 'posix')
  assert.deepEqual(settings.policy.packModes, { 'core.fs': 'warn' })
  assert.equal(settings.audit.retentionDays, 30)
  assert.ok(warnings.length >= 6, `expected several warnings, got ${warnings.length}`)
})

await check('policy settings are parsed', () => {
  const { settings } = normalizeConfig({
    policy: {
      packs: ['core.git', ' core.filesystem ', ''],
      defaultMode: 'deny',
      observeUntil: '2026-11-30',
      packModes: { 'core.git': 'warn' },
    },
  })
  assert.deepEqual(settings.policy.packs, ['core.git', 'core.filesystem'])
  assert.equal(settings.policy.defaultMode, 'deny')
  assert.equal(settings.policy.observeUntil, '2026-11-30')
})

await check('paths land under DSH_HOME', () => {
  const env = { DSH_HOME: path.join(os.tmpdir(), 'dsh-test-home') }
  assert.equal(policyPath(env), path.join(env.DSH_HOME, 'dsh-shell-dcg', 'generated', 'policy.toml'))
  assert.equal(auditDir(env), path.join(env.DSH_HOME, 'dsh-shell-dcg', 'audit'))
})

await check('extractCommand reads command, then script_path', () => {
  const { settings } = normalizeConfig({})
  assert.equal(extractCommand(settings, { command: ' ls ' }), ' ls ')
  assert.deepEqual(extractCommand(settings, { script_path: '/tmp/x.sh' }), { scriptPath: '/tmp/x.sh' })
  assert.equal(extractCommand(settings, { command: '   ', workdir: '.' }), undefined)
  assert.equal(extractCommand(settings, undefined), undefined)
})

await check('compareVersions orders dotted versions', () => {
  assert.ok(compareVersions('0.17.0', '0.16.0') > 0)
  assert.ok(compareVersions('0.16.0', '0.16.0') === 0)
  assert.ok(compareVersions('0.9.9', '0.16.0') < 0)
  assert.ok(compareVersions('0.17.0-rc.1', '0.17.0') === 0)
})

// ---------------------------------------------------------------- policy ----

await check('empty policy emits only the header', () => {
  const { settings } = normalizeConfig({})
  const text = policyToml(settings)
  assert.match(text, /Generated by dsh-shell-dcg/)
  assert.ok(!text.includes('[packs]'))
  assert.ok(!text.includes('[policy]'))
})

await check('policy renders packs, modes, and the observe window', () => {
  const { settings } = normalizeConfig({
    policy: {
      packs: ['core.git', 'windows.filesystem'],
      defaultMode: 'ask',
      observeUntil: '2026-11-30',
      packModes: { 'core.git': 'warn' },
    },
  })
  const text = policyToml(settings)
  assert.match(text, /\[packs\]\nenabled = \["core\.git", "windows\.filesystem"\]/)
  assert.match(text, /\[policy\]\ndefault_mode = "ask"\nobserve_until = "2026-11-30"/)
  assert.match(text, /\[policy\.packs\]\n"core\.git" = "warn"/)
})

// ------------------------------------------------------------- dcg argv ----

await check('argv matches the documented invocation', () => {
  assert.deepEqual(
    buildTestArgs({ dialect: 'posix', policyPath: 'C:\\p\\policy.toml', agentName: 'dsh' }),
    ['--robot', 'test', '--stdin', '--format', 'json', '--dialect', 'posix', '--config', 'C:\\p\\policy.toml', '--agent', 'dsh'],
  )
  assert.deepEqual(buildTestArgs({ dialect: 'ps' }), ['--robot', 'test', '--stdin', '--format', 'json', '--dialect', 'ps'])
})

await check('cleanEnv strips DCG_* so a shell cannot bypass the gate', () => {
  const env = cleanEnv({ DCG_BYPASS: '1', DCG_CONFIG: 'x', PATH: '/bin', HOME: '/home/me' })
  assert.deepEqual(env, { PATH: '/bin', HOME: '/home/me' })
})

// ------------------------------------------------------------- verdicts ----

await check('parseVerdict accepts a known decision', () => {
  const parsed = parseVerdict({
    code: 1,
    stdout: JSON.stringify({ decision: 'deny', rule_id: 'core.git:reset-hard', severity: 'critical', reason: 'nope' }),
  })
  assert.equal(parsed.ok, true)
  assert.equal(parsed.verdict.rule_id, 'core.git:reset-hard')
})

await check('parseVerdict rejects unknown decisions, junk, and silence', () => {
  assert.equal(parseVerdict({ code: 0, stdout: '{"decision":"maybe"}' }).ok, false)
  assert.equal(parseVerdict({ code: 0, stdout: 'not json' }).ok, false)
  assert.equal(parseVerdict({ code: 0, stdout: '   ' }).ok, false)
  assert.equal(parseVerdict({ code: 0, stdout: '[]' }).ok, false)
  assert.equal(parseVerdict({ code: 0, stdout: '{"rule_id":"x"}' }).ok, false)
})

await check('mapDecision honours the configured actions', () => {
  const strict = normalizeConfig({ onAsk: 'deny', onWarn: 'ask' }).settings
  assert.equal(mapDecision('allow', strict), 'allow')
  assert.equal(mapDecision('deny', strict), 'deny')
  assert.equal(mapDecision('ask', strict), 'deny')
  assert.equal(mapDecision('warn', strict), 'ask')
  assert.equal(mapDecision('log', strict), 'ask')
  assert.equal(mapDecision('indeterminate', strict), 'deny')
  assert.equal(mapDecision('something-new', strict), 'deny')

  const lenient = normalizeConfig({ failClosed: false, onAsk: 'allow' }).settings
  assert.equal(mapDecision('ask', lenient), 'allow')
  assert.equal(mapDecision('indeterminate', lenient), 'allow')
})

await check('reasonFor names the rule and stays bounded', () => {
  const text = reasonFor({ decision: 'deny', rule_id: 'core.git:reset-hard', severity: 'critical', reason: 'destroys work' }, '0.17.0')
  assert.match(text, /core\.git:reset-hard/)
  assert.match(text, /dcg 0\.17\.0/)
  assert.ok(text.length <= 1200)
  const long = reasonFor({ decision: 'deny', reason: 'x'.repeat(5000) })
  assert.ok(long.length <= 1201)
})

// -------------------------------------------------------------- process ----

await check('resolveBinary prefers an existing configured path', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-shell-dcg-'))
  const binary = path.join(directory, 'dcg')
  fs.writeFileSync(binary, '')
  const resolved = resolveBinary({ preferManaged: false, dcgPath: binary })
  assert.equal(resolved.path, binary)
  assert.equal(resolved.source, 'config')

  const missing = resolveBinary({ preferManaged: false, dcgPath: path.join(directory, 'nope') }, { PATH: '' })
  assert.equal(missing.path, undefined)
  assert.ok(missing.considered.length >= 1)
  fs.rmSync(directory, { recursive: true, force: true })
})

await check('runDcg captures stdout from a real child process', async () => {
  const result = await runDcg(process.execPath, ['-e', 'process.stdout.write("hello")'], { timeoutMs: 10000 })
  assert.equal(result.failure, undefined)
  assert.equal(result.stdout, 'hello')
  assert.equal(result.code, 0)
})

await check('runDcg reports a timeout instead of hanging', async () => {
  const started = Date.now()
  const result = await runDcg(process.execPath, ['-e', 'setTimeout(() => {}, 5000)'], { timeoutMs: 300 })
  assert.match(String(result.failure), /timed out/)
  assert.ok(Date.now() - started < 4000)
})

await check('runDcg surfaces a missing executable', async () => {
  const result = await runDcg(path.join(os.tmpdir(), 'definitely-not-dcg'), [], { timeoutMs: 1000 })
  assert.match(String(result.failure), /cannot/)
})

await check('createLimiter never exceeds the cap', async () => {
  const limit = createLimiter(2)
  let active = 0
  let peak = 0
  await Promise.all(
    Array.from({ length: 8 }, () =>
      limit(async () => {
        active += 1
        peak = Math.max(peak, active)
        await new Promise((resolve) => setTimeout(resolve, 10))
        active -= 1
      }),
    ),
  )
  assert.equal(peak, 2)
})

// ----------------------------------------------------------------- go/no ----

const failed = results.filter((result) => !result.ok)
process.stdout.write(`\n${results.length - failed.length}/${results.length} passed\n`)
if (failed.length > 0) process.exitCode = 1

const results = []
async function check(name, fn) {
  try {
    await fn()
    results.push({ name, ok: true })
    process.stdout.write(`ok   ${name}\n`)
  } catch (error) {
    results.push({ name, ok: false, error })
    process.stdout.write(`FAIL ${name}\n     ${error instanceof Error ? error.message : String(error)}\n`)
  }
}

